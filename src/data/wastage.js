export function getWastageAnswer(question) {
  const normalizedQuestion = String(question ?? '').toLocaleLowerCase('ka').trim()
  const hasWastageIntent = /დანაკარგ|დანაკარგებ|დანაკარგის|wastage/.test(normalizedQuestion)

  const product = WASTAGE_PRODUCTS
    .flatMap((item) => [item.name, ...(item.aliases ?? [])]
      .map((name) => ({ item, name: name.toLocaleLowerCase('ka') })))
    .sort((first, second) => second.name.length - first.name.length)
    .find(({ name }) => normalizedQuestion.includes(name))

  if (!product || (!hasWastageIntent && normalizedQuestion !== product.name)) return ''

  const lossDetails = product.item.losses
    .map(([operation, percent]) => `• ${operation}: ${percent}`)
    .join('\n')

  return `${product.item.name} — ბუნებრივი დანაკარგის მაქსიმალური ზღვრული ნორმები (დანაკარგი წონიდან):\nსეს ესნ კოდი: ${product.item.codes}\n${lossDetails}\n\nდამატებითი ინფორმაცია: /wastage`
}
